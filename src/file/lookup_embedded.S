#include "../defs.S"

// ─────────────────────────────────────────────────────────────────────
// Function Name: lookup_embedded
//
// Description: Look up a path in the embedded files table (generated by
//   embed_www.sh). The table is sorted lexicographically by path, so
//   binary search gives O(log n) lookup instead of linear scan.
//   Currently uses a DEBUG linear-scan fallback to verify entry layout.
//   References the external symbols embedded_files and embedded_count
//   (declared in the generated/stub files); calls streqn.
//
// Input/Arguments:
//   x0 -> path string (e.g. "www/index.html")
//   x1 -> path length
//
// Output/Returns:
//   x0 -> content pointer
//   x1 -> content size
//   x2 -> content-type string pointer
//   x3 -> content-type string length
//   x4 -> gzip flag (1 = gzipped, 0 = raw)
//   x5 -> ETag string pointer (e.g. "\"abc123...\"")
//   x6 -> ETag string length
//   carry set = not found, carry clear = found
//
// Clobbered Registers:
//   x0-x6, x9, x10, x19-x24 (x19-x24 saved and restored)
//
// Stack Usage:
//   64 bytes: stp x29, x30, [sp, #-64]!
// ─────────────────────────────────────────────────────────────────────

.text
.align 2
.global lookup_embedded
lookup_embedded:
    stp x29, x30, [sp, #-64]!
    stp x19, x20, [sp, #16]
    stp x21, x22, [sp, #32]
    stp x23, x24, [sp, #48]

    mov x19, x0  // save path_ptr
    mov x20, x1  // save path_len

    // DEBUG: linear scan fallback to verify entry layout
    adr_l x5, embedded_files
    mov x9, #80                  // entry size
    adr_l x10, embedded_count
    ldr x22, [x10]              // x22 = count
    mov x23, #0                 // index

Lle_linear_scan:
    cmp x23, x22
    b.ge Lle_not_found

    mul x6, x23, x9             // offset = index * 80
    add x6, x5, x6              // x6 = &embedded_files[index]

    ldr x1, [x6, #8]            // entry path_ptr
    ldr x3, [x6, #16]           // entry path_len
    cmp x20, x3                 // compare lengths
    b.ne Lle_linear_next

    mov x0, x19
    mov x2, x20
    bl streqn
    cbnz x0, Lle_found_from_linear

Lle_linear_next:
    add x23, x23, #1
    b Lle_linear_scan

Lle_found_from_linear:
    // x6 already points to the entry
    b Lle_found

Lle_found:
    // Entry layout at x6:
    // +0:  hash        (8 bytes)
    // +8:  path_ptr    (8 bytes)
    // +16: path_len    (8 bytes)
    // +24: content_ptr (8 bytes)
    // +32: content_size (8 bytes)
    // +40: ct_ptr      (8 bytes)
    // +48: ct_len      (8 bytes)
    // +56: gzip flag   (8 bytes)
    // +64: etag_ptr    (8 bytes)
    // +72: etag_len    (8 bytes)
    ldr x0, [x6, #24]   // content_ptr
    ldr x1, [x6, #32]   // content_size
    ldr x2, [x6, #40]   // ct_ptr
    ldr x3, [x6, #48]   // ct_len
    ldr x4, [x6, #56]   // gzip flag
    ldr x5, [x6, #64]   // etag_ptr
    ldr x6, [x6, #72]   // etag_len

    cmn xzr, xzr  // clear carry
    b Lle_epilogue

Lle_not_found:
    cmp xzr, xzr  // set carry
    b Lle_epilogue

Lle_epilogue:
    ldp x23, x24, [sp, #48]
    ldp x21, x22, [sp, #32]
    ldp x19, x20, [sp, #16]
    ldp x29, x30, [sp], #64
    ret
