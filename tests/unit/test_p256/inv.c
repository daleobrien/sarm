static void test_inv(void) {
    TEST_SUITE("p256_fe_inv — a^-1 mod p");

    for (int i = 0; i < NINV; i++) {
        uint64_t a[4], out[4];
        uint8_t outb[32];
        p256_fe_frombytes(a, INVS[i].a);
        p256_fe_inv(out, a);
        p256_fe_tobytes(outb, out);
        ASSERT_EQ("a^-1 mod p", 0, memcmp(outb, INVS[i].inv, 32));
    }

    // a * a^-1 == 1 for every non-zero vector.
    for (int i = 1; i < NINV; i++) {
        uint64_t a[4], ainv[4], one[4];
        uint8_t oneb[32];
        p256_fe_frombytes(a, INVS[i].a);
        p256_fe_inv(ainv, a);
        p256_fe_mul(one, a, ainv);
        p256_fe_tobytes(oneb, one);
        ASSERT_EQ("a * a^-1 == 1", 1, oneb[31] == 1);
        int rest_zero = 1;
        for (int j = 0; j < 31; j++) {
            if (oneb[j] != 0) rest_zero = 0;
        }
        ASSERT_EQ("a * a^-1 high bytes are zero", 1, rest_zero);
    }
}

