static void test_frombytes_tobytes(void) {
    TEST_SUITE("p256_fe_frombytes / p256_fe_tobytes — roundtrip against P");

    for (int i = 0; i < NVALS; i++) {
        uint64_t fe[4];
        uint8_t out[32];
        p256_fe_frombytes(fe, VALS[i]);
        p256_fe_tobytes(out, fe);
        ASSERT_EQ("roundtrip matches input", 0, memcmp(out, VALS[i], 32));
    }

    // Known-value spot check: 1 -> limb0 = 1, limbs 1-3 = 0.
    uint64_t one[4];
    p256_fe_frombytes(one, VALS[1]);
    ASSERT_EQ("fe(1) limb0", 1, (int64_t)one[0]);
    ASSERT_EQ("fe(1) limb1", 0, (int64_t)one[1]);
    ASSERT_EQ("fe(1) limb2", 0, (int64_t)one[2]);
    ASSERT_EQ("fe(1) limb3", 0, (int64_t)one[3]);
}

