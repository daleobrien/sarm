// Unit tests for tls_app_data_write from
// src/tls/record/application_write.S (RFC 8446 §5.2, §23.3)
//
// tls_app_data_write reads the server application key/IV from
// tls_state's TLS_SERVER_APP_KEY/TLS_SERVER_APP_IV fields and takes
// the next sequence number from tls_server_seq (incrementing it), so
// each vector below sets those globals directly before calling.
//
// The first vector is RFC 8448 §3's own server application_data
// record (RFC_SAP_KEY/RFC_SAP_IV, seq 1 — the NewSessionTicket was the
// server's seq 0) — the strongest possible cross-check, an
// independently published test vector rather than anything generated
// by this project. The rest are generated in Python via
// cryptography.hazmat.primitives.ciphers.aead.AESGCM (an independent,
// audited AES-GCM implementation), covering multiple lengths
// including the zero-and-one-byte edge cases.

#include "test_harness.h"

extern uint8_t tls_server_app_key[16] __asm__("tls_server_app_key");
extern uint8_t tls_server_gcm_ctx[304] __asm__("tls_server_gcm_ctx");
extern void aes_gcm_ctx_init(const void *key, void *ctx)
    __asm__("aes_gcm_ctx_init");

// See read.c: tls_app_data_write seals with tls_server_gcm_ctx, so a
// hand-installed key needs its context rebuilt alongside it.
static void install_server_app_key(const uint8_t key[16]) {
    memcpy(tls_server_app_key, key, 16);
    aes_gcm_ctx_init(tls_server_app_key, tls_server_gcm_ctx);
}
extern uint8_t tls_server_app_iv[12] __asm__("tls_server_app_iv");
extern uint64_t tls_server_seq __asm__("tls_server_seq");

// tls_app_data_write(pt=x0, pt_len=x1, out=x2) -> x0 = record length on
// success; error code + carry set on failure.
static uint64_t app_write(const uint8_t *pt, uint64_t pt_len, uint8_t *out,
                          uint64_t *carry) {
    uint64_t result, c;
    __asm__ volatile(
        "cmp xzr, xzr\n"
        "mov x0, %2\n"
        "mov x1, %3\n"
        "mov x2, %4\n"
        "bl tls_app_data_write\n"
        "cset %1, cs\n"
        "mov %0, x0\n"
        : "=r"(result), "=r"(c)
        : "r"(pt), "r"(pt_len), "r"(out)
        : "x0", "x1", "x2", "x3", "x4", "x5", "x6", "x7", "x8", "x9",
          "x10", "x11", "x12", "x19", "x20", "x21", "x22", "x23", "x24",
          "x30", "v0", "v1", "v2", "v3", "v4", "v5", "v6", "v7",
          "v16", "v17", "v18", "v19", "v20", "v21", "cc", "memory");
    *carry = c;
    return result;
}

// RFC 8448 §3 — server_application_traffic_secret_0 write key/iv
static const uint8_t RFC_SAP_KEY[16] = {
    0x9f, 0x02, 0x28, 0x3b, 0x6c, 0x9c, 0x07, 0xef,
    0xc2, 0x6b, 0xb9, 0xf2, 0xac, 0x92, 0xe3, 0x56,
};
static const uint8_t RFC_SAP_IV[12] = {
    0xcf, 0x78, 0x2b, 0x88, 0xdd, 0x83, 0x54, 0x9a, 0xad, 0xf1, 0xe9, 0x84,
};
// the server's application_data record (72 octets), 50-octet ascending
// payload, seq 1 (NewSessionTicket was seq 0 in the RFC 8448 trace)
