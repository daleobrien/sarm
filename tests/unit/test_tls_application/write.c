static void test_write(void) {
    TEST_SUITE("tls_app_data_write — matches Python/cryptography reference");
    for (size_t i = 0; i < NWR; i++) {
        install_server_app_key(WRS[i].key);
        memcpy(tls_server_app_iv, WRS[i].iv, 12);
        tls_server_seq = WRS[i].seq;

        uint8_t out[256];
        uint64_t carry = 0;
        uint64_t n = app_write(WRS[i].pt, WRS[i].pt_len, out, &carry);
        ASSERT_EQ("carry clear", 0, (int)carry);
        ASSERT_EQ("record length matches", (int)WRS[i].rec_len, (int)n);
        ASSERT_TRUE("record bytes match",
                    memcmp(out, WRS[i].rec, WRS[i].rec_len) == 0);
        ASSERT_EQ("server_seq incremented", (int)(WRS[i].seq + 1),
                  (int)tls_server_seq);
    }
}

static void test_length_error(void) {
    TEST_SUITE("tls_app_data_write — oversized plaintext rejected");
    install_server_app_key(WRS[0].key);
    memcpy(tls_server_app_iv, WRS[0].iv, 12);
    tls_server_seq = 0;

    static uint8_t huge[16400];
    uint8_t out[16640 + 64];
    uint64_t carry = 0;
    uint64_t err = app_write(huge, sizeof(huge), out, &carry);
    ASSERT_EQ("carry set", 1, (int)carry);
    ASSERT_EQ("TLS_RECORD_ERR_LENGTH", 4, (int)err);
}

