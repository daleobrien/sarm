static void test_secrets(void) {
    TEST_SUITE("tls_derive_application_secrets — matches Python reference");
    for (size_t i = 0; i < NAS; i++) {
        memcpy(tls_master_secret, VECS[i].master_secret, 32);
        tls_derive_application_secrets(VECS[i].transcript_hash);
        ASSERT_TRUE("client_app_key matches",
                    memcmp(tls_client_app_key, VECS[i].client_key, 16) == 0);
        ASSERT_TRUE("client_app_iv matches",
                    memcmp(tls_client_app_iv, VECS[i].client_iv, 12) == 0);
        ASSERT_TRUE("server_app_key matches",
                    memcmp(tls_server_app_key, VECS[i].server_key, 16) == 0);
        ASSERT_TRUE("server_app_iv matches",
                    memcmp(tls_server_app_iv, VECS[i].server_iv, 12) == 0);
    }
}

static void test_resets_sequence_numbers(void) {
    TEST_SUITE("tls_derive_application_secrets — key change resets seqs (§5.3)");
    tls_client_seq = 7;
    tls_server_seq = 9;
    memcpy(tls_master_secret, VECS[0].master_secret, 32);
    tls_derive_application_secrets(VECS[0].transcript_hash);
    ASSERT_EQ("client_seq reset to 0", 0, (int)tls_client_seq);
    ASSERT_EQ("server_seq reset to 0", 0, (int)tls_server_seq);
}

static void test_different_transcript_differs(void) {
    TEST_SUITE("tls_derive_application_secrets — transcript-dependence");
    memcpy(tls_master_secret, VECS[0].master_secret, 32);
    tls_derive_application_secrets(VECS[0].transcript_hash);
    uint8_t key1[16];
    memcpy(key1, tls_server_app_key, 16);

    uint8_t other_hash[32];
    memcpy(other_hash, VECS[0].transcript_hash, 32);
    other_hash[0] ^= 0xff;
    tls_derive_application_secrets(other_hash);

    int same = memcmp(key1, tls_server_app_key, 16) == 0;
    ASSERT_EQ("server_app_key changes with the transcript hash", 0, same);
}

int main(void) {
    test_secrets();
    test_resets_sequence_numbers();
    test_different_transcript_differs();
    test_summary();
    return 0;
}
