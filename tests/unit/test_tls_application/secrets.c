// Unit tests for tls_derive_application_secrets from
// src/tls/handshake/application_secrets.S (RFC 8446 §7.1, §5.3)
//
// tls_derive_application_secrets reads its input (the Master Secret)
// from tls_state's TLS_MASTER_SECRET field (tls_master_secret) and
// takes the CH..server-Finished transcript hash as an argument, so
// each vector below sets that global directly before calling. Vectors
// are (master_secret, transcript_hash) -> (client_app_key, client_
// app_iv, server_app_key, server_app_iv), computed in Python with a
// from-scratch HMAC-SHA256 HKDF-Expand-Label implementation that was
// cross-checked, derivation by derivation, against
// cryptography.hazmat.primitives.kdf.hkdf.HKDFExpand (an independent,
// audited implementation) before being used to generate these
// vectors — this is a mechanical composition of already-verified
// primitives (hkdf_expand_label), not new algorithmic content, so no
// from-scratch Python re-derivation of the underlying math was needed
// (see the verified-asm-crypto skill's "when this doesn't apply"
// exception).

