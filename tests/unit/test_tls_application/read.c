static void test_read_rfc8448(void) {
    TEST_SUITE("tls_app_data_read — RFC 8448 §3 client application_data");
    install_client_app_key(RFC_CAP_KEY);
    memcpy(tls_client_app_iv, RFC_CAP_IV, 12);
    tls_client_seq = 0;

    uint8_t out[128];
    uint64_t carry = 0, inner = 0;
    uint64_t n = app_read(RFC_CLIENT_APP, 72, out, &inner, &carry);
    ASSERT_EQ("carry clear", 0, (int)carry);
    ASSERT_EQ("content length is 50", 50, (int)n);
    ASSERT_EQ("inner type is application_data (23)", 23, (int)inner);
    for (int i = 0; i < 50; i++)
        ASSERT_EQ("payload byte matches ascending fill", i, out[i]);
    ASSERT_EQ("client_seq incremented to 1", 1, (int)tls_client_seq);
}

