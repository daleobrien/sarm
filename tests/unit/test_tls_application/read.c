static void test_read(void) {
    TEST_SUITE("tls_app_data_read — matches Python/cryptography reference");
    for (size_t i = 0; i < NRD; i++) {
        install_client_app_key(RDS[i].key);
        memcpy(tls_client_app_iv, RDS[i].iv, 12);
        tls_client_seq = RDS[i].seq;

        uint8_t out[256];
        uint64_t carry = 0, inner = 0;
        uint64_t n = app_read(RDS[i].rec, RDS[i].rec_len, out, &inner, &carry);
        ASSERT_EQ("carry clear", 0, (int)carry);
        ASSERT_EQ("content length matches", (int)RDS[i].pt_len, (int)n);
        ASSERT_EQ("inner type matches", (int)RDS[i].inner, (int)inner);
        if (RDS[i].pt_len)
            ASSERT_TRUE("plaintext matches",
                        memcmp(out, RDS[i].pt, RDS[i].pt_len) == 0);
        ASSERT_EQ("client_seq incremented", (int)(RDS[i].seq + 1),
                  (int)tls_client_seq);
    }
}

static void test_mac_failure(void) {
    TEST_SUITE("tls_app_data_read — tampered tag rejected");
    install_client_app_key(RDS[0].key);
    memcpy(tls_client_app_iv, RDS[0].iv, 12);
    tls_client_seq = RDS[0].seq;

    uint8_t tampered[27];
    memcpy(tampered, RDS[0].rec, 27);
    tampered[26] ^= 0xff;               // flip the last tag byte

    uint8_t out[256];
    uint64_t carry = 0, inner = 0;
    uint64_t err = app_read(tampered, 27, out, &inner, &carry);
    ASSERT_EQ("carry set", 1, (int)carry);
    ASSERT_EQ("TLS_RECORD_ERR_MAC", 6, (int)err);
}

