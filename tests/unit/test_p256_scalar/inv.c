static void test_inv(void) {
    TEST_SUITE("p256_scalar_inv — a^-1 mod n");
    for (int i = 0; i < NSCINV; i++) {
        uint64_t a[4], out[4];
        uint8_t outb[32];
        p256_fe_frombytes(a, SCINVS[i].a);
        p256_scalar_inv(out, a);
        p256_fe_tobytes(outb, out);
        ASSERT_EQ("a^-1 mod n", 0, memcmp(outb, SCINVS[i].inv, 32));
    }

    for (int i = 1; i < NSCINV; i++) {
        uint64_t a[4], ainv[4], one[4];
        uint8_t oneb[32];
        p256_fe_frombytes(a, SCINVS[i].a);
        p256_scalar_inv(ainv, a);
        p256_scalar_mul(one, a, ainv);
        p256_fe_tobytes(oneb, one);
        int ok = (oneb[31] == 1);
        for (int j = 0; j < 31; j++) if (oneb[j] != 0) ok = 0;
        ASSERT_EQ("a * a^-1 == 1", 1, ok);
    }
}

