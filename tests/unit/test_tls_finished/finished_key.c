#define NFK (sizeof(FKS) / sizeof(FKS[0]))

static void test_finished_key(void) {
    TEST_SUITE("tls_finished_key — cross-checked against cryptography.HKDFExpand");
    for (size_t i = 0; i < NFK; i++) {
        uint8_t out[32];
        tls_finished_key(FKS[i].base_key, out);
        ASSERT_TRUE("finished_key matches", memcmp(out, FKS[i].expected, 32) == 0);
    }
}

static void test_deterministic(void) {
    TEST_SUITE("tls_finished_key — deterministic");
    uint8_t out1[32], out2[32];
    tls_finished_key(FKS[0].base_key, out1);
    tls_finished_key(FKS[0].base_key, out2);
    ASSERT_TRUE("repeated call reproduces the same key", memcmp(out1, out2, 32) == 0);
}

