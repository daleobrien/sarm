#define NWR (sizeof(WRS) / sizeof(WRS[0]))

static void test_write(void) {
    TEST_SUITE("tls_finished_write — matches Python reference");
    for (size_t i = 0; i < NWR; i++) {
        memcpy(tls_server_hs_traffic_secret, WRS[i].base_key, 32);
        uint8_t out[36];
        uint64_t len = tls_finished_write(out, WRS[i].transcript_hash);
        ASSERT_EQ("message length is 36", 36, (int)len);
        ASSERT_TRUE("message matches", memcmp(out, WRS[i].msg, 36) == 0);
    }
}

static void test_header_fields(void) {
    TEST_SUITE("tls_finished_write — handshake header");
    memcpy(tls_server_hs_traffic_secret, WRS[0].base_key, 32);
    uint8_t out[36];
    tls_finished_write(out, WRS[0].transcript_hash);
    ASSERT_EQ("type == TLS_HS_FINISHED (20)", 20, out[0]);
    ASSERT_EQ("length byte 0", 0, out[1]);
    ASSERT_EQ("length byte 1", 0, out[2]);
    ASSERT_EQ("length byte 2 == 32", 32, out[3]);
}

