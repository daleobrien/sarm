// Run the NIST vectors through the full asm seal pipeline
// (acceptance).
static void test_gcm_encrypt_kat(void) {
    TEST_SUITE("aes_gcm_encrypt NIST SP 800-38D vectors");
    uint8_t ct[128], tag[16];
    int failures = 0;

    aes_gcm_encrypt(TC1_KEY, TC1_IV, TC1_AAD, TC1_AAD_LEN, TC1_PT,
                    TC1_PT_LEN, ct, tag);
    if (memcmp(tag, TC1_TAG, 16) != 0) {
        _FAIL("TC1 tag mismatch");
        failures++;
    }
    aes_gcm_encrypt(TC2_KEY, TC2_IV, TC2_AAD, TC2_AAD_LEN, TC2_PT,
                    TC2_PT_LEN, ct, tag);
    if (memcmp(ct, TC2_CT, TC2_PT_LEN) != 0 || memcmp(tag, TC2_TAG, 16) != 0) {
        _FAIL("TC2 ct/tag mismatch");
        failures++;
    }
    aes_gcm_encrypt(TC3_KEY, TC3_IV, TC3_AAD, TC3_AAD_LEN, TC3_PT,
                    TC3_PT_LEN, ct, tag);
    if (memcmp(ct, TC3_CT, TC3_PT_LEN) != 0 || memcmp(tag, TC3_TAG, 16) != 0) {
        _FAIL("TC3 ct/tag mismatch");
        failures++;
    }
    aes_gcm_encrypt(TC4_KEY, TC4_IV, TC4_AAD, TC4_AAD_LEN, TC4_PT,
                    TC4_PT_LEN, ct, tag);
    if (memcmp(ct, TC4_CT, TC4_PT_LEN) != 0 || memcmp(tag, TC4_TAG, 16) != 0) {
        _FAIL("TC4 ct/tag mismatch");
        failures++;
    }
    ASSERT_EQ("all NIST encrypt vectors pass", 0, failures);
}


// Sweep the plaintext lengths that decide how encrypt.S's four-block CTR
// loop splits into groups, leftover full blocks and a partial tail.
static void test_gcm_encrypt_ctr_lengths(void) {
    TEST_SUITE("aes_gcm_encrypt CTR length sweep");
    uint8_t ct[256], tag[16];
    int failures = 0;

    for (size_t i = 0; i < sizeof(SWEEP) / sizeof(SWEEP[0]); i++) {
        const struct sweep_vec *v = &SWEEP[i];
        memset(ct, 0xA5, sizeof(ct));
        aes_gcm_encrypt(SWEEP_KEY, SWEEP_IV, v->aad, v->aad_len,
                        v->pt, v->pt_len, ct, tag);
        if (v->pt_len && memcmp(ct, v->ct, v->pt_len) != 0) {
            _FAIL("%s ciphertext mismatch", v->name);
            failures++;
        } else if (memcmp(tag, v->tag, 16) != 0) {
            _FAIL("%s tag mismatch", v->name);
            failures++;
        } else if (ct[v->pt_len] != 0xA5) {
            _FAIL("%s wrote past pt_len", v->name);
            failures++;
        }
    }
    ASSERT_EQ("all CTR sweep lengths pass", 0, failures);
}

int main(void) {
    test_gcm_encrypt_kat();
    test_gcm_encrypt_ctr_lengths();
    test_summary();
    return 0;
}
